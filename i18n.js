const switcher = document.querySelector('#languageSwitcher');
let activeLanguage = localStorage.getItem('noel-language') || 'en';
window.getSignalWords = () => translations[activeLanguage].words;
window.applyLanguage = () => {
    const t = translations[activeLanguage];
    document.documentElement.lang = activeLanguage;
    document.querySelectorAll('[data-i18n]').forEach(el => el.textContent = t[el.dataset.i18n] || el.textContent);
    document.querySelectorAll('[data-i18n-html]').forEach(el => el.innerHTML = t[el.dataset.i18nHtml] || el.innerHTML);
    switcher.value = activeLanguage;
    document.querySelector('#signalWord').textContent = t.words[0]
}
;
switcher.addEventListener('change', () => {
    activeLanguage = switcher.value;
    localStorage.setItem('noel-language', activeLanguage);
    window.applyLanguage()
}
);
window.applyLanguage();
